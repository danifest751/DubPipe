import { describe, expect, it } from 'vitest';
import { judgeClip } from '../src/core/clip-check.js';

/**
 * Сверка озвученного с текстом. Примеры — настоящие: текст реплики ролика
 * FRANCE 24 и то, что распознавание услышало в клипах X-Voice.
 */

describe('проверка озвученной реплики', () => {
  it('промахи распознавания браком не считает', () => {
    expect(judgeClip('Теперь в Anthropic заявляют, что провели продуктивные переговоры', 'Теперь в антропик заявляют, что провели продуктивные переговоры.').ok).toBe(true);
    expect(judgeClip('Конечно, Anthropic и администрация Трампа сталкивались лбами и раньше.', 'Конечно, антропики администрация Трампа сталкивались с львами и раньше.').ok).toBe(true);
    expect(judgeClip('Питер О\'Брайен подготовил для нас обзор.', 'Питер Абрайан подготовил для нас обзор.').ok).toBe(true);
    // Короткое служебное слово в конце распознавание теряет само.
    expect(judgeClip('Взглянем на...', 'Взглянем.').ok).toBe(true);
  });

  it('имена и междометия, на которых ошибается распознавание, браком не считает', () => {
    // Эпизод 8: имя путают по гласным и разбивают надвое.
    expect(judgeClip('Итан, посмотри на меня.', 'Эйтан, посмотри на меня.').ok).toBe(true);
    expect(judgeClip('Кедра Натарсоа?', 'Кедра на тарса.').ok).toBe(true);
    // На полусекунде «Ох...» распознавание выдумывает фразу целиком.
    expect(judgeClip('Ох...', 'Продолжение следует...').ok).toBe(true);
  });

  it('ловит договорённый обрывок образца в начале', () => {
    const verdict = judgeClip('с правительством, и что модели снова запущены', 'Сейшен с правительством и что модели снова запущены');
    expect(verdict.ok).toBe(false);
    expect(verdict.problems).toContain('junk-start');
    // Распознавание может приклеить обрывок к первому слову.
    expect(judgeClip('Системы отключили после того, как власти заявили', 'сейшнсистемы отключили после того как власти заявили').problems).toContain('junk-start');
  });

  it('ловит пропавший конец и пропавшее начало', () => {
    expect(judgeClip('Теперь в Anthropic заявляют, что провели продуктивные переговоры', 'Теперь в Anthropic заявляют, что провели продуктивные').problems).toEqual(['lost-end']);
    expect(judgeClip('Anthropic согласилась заранее выявлять', 'Антропик согласилась заранее.').problems).toEqual(['lost-end']);
    expect(judgeClip('По данным New York Post, администрация Трампа сменила курс', 'Пост администрация Трампа сменила курс').problems).toContain('lost-start');
  });

  it('ловит неразборчивое и пустое', () => {
    expect(judgeClip('Они будут внедрять общие стандарты для выявления взломов', 'они будут ну это самое').problems).toContain('garbled');
    expect(judgeClip('Всё дело в национальной безопасности.', '').ok).toBe(false);
  });

  it('лучшая попытка — с большим счётом', () => {
    const clean = judgeClip('с правительством, и что модели снова запущены', 'с правительством и что модели снова запущены');
    const junk = judgeClip('с правительством, и что модели снова запущены', 'сейшен с правительством и что модели снова запущены');
    expect(clean.score).toBeGreaterThan(junk.score);
  });
});
